"""Chronological validation: train on earlier origination years, evaluate on the next one.

    python -m loan_default.temporal        # writes reports/temporal_validation.md

Shuffled cross-validation mixes years, so every fold trains on loans issued after the
ones it is scored on. Here each evaluation year is scored by a model trained only on
the years before it, the way the model would be used. The last row, 2016, is the test
sample scored by a model trained on all of 2007-2015.
"""

import argparse
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

from loan_default.policy import approve_safest
from loan_default.preprocessing import load_split
from loan_default.train import TrainConfig, build_model, default_scores, out_of_fold_scores

EVALUATION_YEARS = (2012, 2013, 2014, 2015)
APPROVAL_RATE = 0.8


def issue_years(X: pd.DataFrame) -> pd.Series:
    """Origination year of each loan."""
    return pd.to_datetime(X["issue_d"]).dt.year


def score_summary(y: pd.Series, scores: np.ndarray) -> dict[str, float]:
    """Ranking, calibration-in-the-large and policy metrics for one evaluation set."""
    actual, predicted = float(y.mean()), float(scores.mean())
    approved = approve_safest(scores, APPROVAL_RATE)
    return {
        "roc_auc": float(roc_auc_score(y, scores)),
        "average_precision": float(average_precision_score(y, scores)),
        "mean_predicted": predicted,
        "actual": actual,
        "gap": actual - predicted,
        "default_rate_at_80": float(np.asarray(y)[approved].mean()),
    }


def forward_chaining(
    X: pd.DataFrame, y: pd.Series, years: pd.Series, evaluation_years: tuple[int, ...], config: TrainConfig
) -> pd.DataFrame:
    """For each evaluation year, fit on all earlier years and score that year."""
    rows = []
    for year in evaluation_years:
        train_mask, eval_mask = years < year, years == year
        model = build_model(config.model_params, config.seed).fit(X[train_mask], y[train_mask])
        scores = default_scores(model, X[eval_mask])
        rows.append(
            {
                "evaluation_year": year,
                "n_train": int(train_mask.sum()),
                "n_eval": int(eval_mask.sum()),
                **score_summary(y[eval_mask], scores),
            }
        )
    return pd.DataFrame(rows)


def render_report(chained: pd.DataFrame, shuffled: dict[str, float]) -> str:
    """Write the comparison as Markdown."""
    lines = [
        "# Chronological validation",
        "",
        "Each row is scored by a model trained only on loans issued in earlier years.",
        "",
        "Generated by `python -m loan_default.temporal`.",
        "",
        "| Evaluated year | Trained on | Evaluated on | ROC-AUC | AP | Mean predicted | Actual | Gap "
        "| Default rate, safest 80% |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for row in chained.itertuples():
        lines.append(
            f"| {row.evaluation_year} | {row.n_train:,} | {row.n_eval:,} | {row.roc_auc:.4f} | "
            f"{row.average_precision:.4f} | {row.mean_predicted * 100:.2f}% | {row.actual * 100:.2f}% | "
            f"{row.gap * 100:+.2f} pp | {row.default_rate_at_80 * 100:.2f}% |"
        )
    lines += [
        "",
        f"Shuffled 5-fold CV on 2007-2015, for comparison: ROC-AUC {shuffled['roc_auc']:.4f}, "
        f"AP {shuffled['average_precision']:.4f}, mean predicted {shuffled['mean_predicted'] * 100:.2f}% "
        f"against {shuffled['actual'] * 100:.2f}% actual.",
        "",
        "Gap = actual default rate minus mean predicted probability; positive means the model understated risk.",
        "",
    ]
    return "\n".join(lines)


def run(config: TrainConfig, out_dir: Path) -> str:
    """Run forward-chaining validation through 2016 and write the report."""
    X_train, y_train = load_split(config.train_path)
    X_test, y_test = load_split(config.test_path)
    X = pd.concat([X_train, X_test], ignore_index=True)
    y = pd.concat([y_train, y_test], ignore_index=True)
    years = issue_years(X)

    chained = forward_chaining(X, y, years, (*EVALUATION_YEARS, int(issue_years(X_test).max())), config)
    oof = out_of_fold_scores(
        build_model(config.model_params, config.seed), X_train, y_train, config.cv_folds, config.seed
    )
    report = render_report(chained, score_summary(y_train, oof))

    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "temporal_validation.md").write_text(report)
    chained.to_csv(out_dir / "temporal_validation.csv", index=False)
    return report


def main(argv: list[str] | None = None) -> None:
    """Run the validation from the command line."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out-dir", type=Path, default=Path("reports"))
    args = parser.parse_args(argv)
    print(run(TrainConfig(), args.out_dir))


if __name__ == "__main__":
    main()
